import os
import re
from typing import Any, Dict, List, Optional, Set, Type
from pydantic import BaseModel
from langchain_core.language_models.chat_models import BaseChatModel
from langchain_core.messages import AIMessage, BaseMessage, HumanMessage, SystemMessage
from langchain_core.outputs import ChatGeneration, ChatResult
from langchain_core.runnables import RunnableLambda

from src.config import settings
from src.utils.logger import get_logger

logger = get_logger("llm")

# Common stop words to exclude from keyword overlap heuristic
STOP_WORDS: Set[str] = {
    "the", "and", "for", "with", "that", "this", "from", "what", "how", "are",
    "can", "you", "does", "have", "been", "will", "would", "should", "could",
    "about", "into", "their", "there", "then", "them", "which", "when", "where",
    "some", "such", "other", "than", "also", "most", "only", "over", "such",
}


class MockChatModel(BaseChatModel):
    """Deterministic, offline mock chat model for testing and environments without Gemini API keys.

    Generates realistic, grounded responses and structured outputs without requiring network access
    or consuming API credits.
    """

    model_name: str = "mock-gemini-1.5-flash"

    @property
    def _llm_type(self) -> str:
        return "mock-chat-model"

    def _generate(
        self,
        messages: List[BaseMessage],
        stop: Optional[List[str]] = None,
        run_manager: Optional[Any] = None,
        **kwargs: Any,
    ) -> ChatResult:
        full_text = " ".join(m.content if isinstance(m.content, str) else str(m.content) for m in messages)
        response_text = self._mock_text_response(full_text)
        generation = ChatGeneration(message=AIMessage(content=response_text))
        return ChatResult(generations=[generation])

    def _mock_text_response(self, prompt: str) -> str:
        prompt_lower = prompt.lower()

        # Query rewrite prompt
        if "rewrite" in prompt_lower or "reformulate" in prompt_lower:
            match = re.search(r"Original Question:\s*([^\n\r]+)", prompt, re.IGNORECASE)
            q = match.group(1).strip() if match else "technical documentation architecture"
            clean_q = re.sub(r"[^\w\s]", "", q)
            return f"{clean_q} overview architecture guide concepts"

        # Answer generation prompt
        if "context:" in prompt_lower and ("user question:" in prompt_lower or "answer:" in prompt_lower):
            # Extract user question
            q_match = re.search(r"User Question:\s*([^\n\r]+)", prompt, re.IGNORECASE)
            question = q_match.group(1).strip() if q_match else "your question"

            # Parse all source context blocks: [Source #X: filename.ext (Title)]\n<content>
            blocks = re.findall(
                r"\[Source #\d+:\s*([^\s()]+)[^\]]*\]\s*([\s\S]*?)(?=(?:\[Source #\d+:|User Question:|$))",
                prompt,
            )

            if blocks:
                synthesized_points = []
                citations = []
                for filename, chunk_text in blocks:
                    clean_text = chunk_text.strip()
                    if not clean_text or clean_text == "---":
                        continue
                    if filename not in citations:
                        citations.append(filename)

                    # Extract paragraphs and code blocks (skipping standalone title headers)
                    paragraphs = [p.strip() for p in clean_text.split("\n\n") if p.strip()]
                    body_paragraphs = [
                        p for p in paragraphs if not (p.startswith("# ") and "\n" not in p)
                    ]
                    for p in (body_paragraphs or paragraphs)[:2]:
                        if len(p) > 20 and not p.startswith("---"):
                            synthesized_points.append(f"- **From `{filename}`**:\n  {p}")

                citation_str = ", ".join([f"[{c}]" for c in citations])
                points_body = "\n\n".join(synthesized_points[:4])

                return (
                    f"Based on the technical documentation, here are the key details answering **{question}**:\n\n"
                    f"{points_body}\n\n"
                    f"*Sources: {citation_str}*"
                )

            return "Based on the provided technical documentation, relevant specifications are described in the indexed context."

        return "This is a response generated by the documentation assistant."

    def with_structured_output(self, schema: Type[BaseModel], **kwargs: Any):
        """Mocks structured output binding by returning an instance of the target Pydantic schema."""

        def _mock_structured_call(input_val: Any) -> BaseModel:
            user_msg = ""
            if isinstance(input_val, list):
                for m in input_val:
                    if isinstance(m, HumanMessage):
                        user_msg = m.content if isinstance(m.content, str) else str(m.content)
            elif isinstance(input_val, str):
                user_msg = input_val
            else:
                user_msg = str(input_val)

            schema_name = schema.__name__.lower()

            # 1. Query Analysis Output
            if "queryanalysis" in schema_name:
                match = re.search(r"User Question:\s*(.+)", user_msg, re.IGNORECASE)
                raw_q = match.group(1).strip() if match else user_msg.strip()

                low_q = raw_q.lower()
                if any(w in low_q for w in ["how to", "how do", "steps", "guide"]):
                    intent = "how-to"
                elif any(w in low_q for w in ["error", "fail", "issue", "troubleshoot", "fix"]):
                    intent = "troubleshooting"
                elif any(w in low_q for w in ["api", "parameter", "function", "signature", "endpoint"]):
                    intent = "api_reference"
                else:
                    intent = "conceptual"

                clean_search = re.sub(r"[?!.,]", "", raw_q).strip()
                return schema(intent=intent, search_query=clean_search)

            # 2. Document Grade Output
            elif "documentgrade" in schema_name or "grade" in schema_name:
                q_match = re.search(r"User Question:\s*(.+?)(?:\n\nDocument Chunk|\Z)", user_msg, re.DOTALL | re.IGNORECASE)
                c_match = re.search(r"Document Chunk.*:\s*([\s\S]+)", user_msg, re.IGNORECASE)

                q_text = q_match.group(1).lower() if q_match else ""
                c_text = c_match.group(1).lower() if c_match else ""

                # Extract content tokens excluding common stop words
                q_tokens = {
                    t for t in re.findall(r"\b[a-z]{3,}\b", q_text) if t not in STOP_WORDS
                }
                c_tokens = {
                    t for t in re.findall(r"\b[a-z]{3,}\b", c_text) if t not in STOP_WORDS
                }

                overlap = q_tokens.intersection(c_tokens)

                if not overlap or "irrelevant" in user_msg.lower():
                    return schema(
                        is_relevant=False,
                        reasoning="No semantic overlap between query keywords and document chunk context.",
                    )
                else:
                    return schema(
                        is_relevant=True,
                        reasoning=f"Document chunk contains relevant context terms: {list(overlap)[:3]}",
                    )

            # Fallback default instantiation
            try:
                return schema()
            except Exception:
                fields = schema.model_fields
                dummy_data = {}
                for k, v in fields.items():
                    if v.annotation == str:
                        dummy_data[k] = "mock_value"
                    elif v.annotation == bool:
                        dummy_data[k] = True
                    elif v.annotation == int:
                        dummy_data[k] = 1
                    else:
                        dummy_data[k] = []
                return schema(**dummy_data)

        return RunnableLambda(_mock_structured_call)


def get_llm(
    provider: Optional[str] = None,
    model: Optional[str] = None,
    temperature: Optional[float] = None,
    api_key: Optional[str] = None,
) -> BaseChatModel:
    """Factory to initialize the appropriate Chat LLM.

    Supports Groq, Google Gemini, OpenAI, and Deterministic Mock.

    Args:
        provider: "groq", "gemini", "openai", or "mock" (defaults to settings.LLM_PROVIDER).
        model: Specific model name (e.g., "llama-3.3-70b-versatile", "gemini-1.5-flash").
        temperature: Sampling temperature (default: 0.0 for deterministic output).
        api_key: Optional explicit API key.

    Returns:
        Instance conforming to LangChain's BaseChatModel.
    """
    selected_provider = (provider or settings.LLM_PROVIDER or "groq").lower()
    
    groq_key = (
        (api_key if provider == "groq" else None)
        or settings.GROQ_API_KEY
        or os.getenv("GROQ_API_KEY")
    )
    gemini_key = (
        (api_key if provider == "gemini" else None)
        or settings.GEMINI_API_KEY
        or settings.GOOGLE_API_KEY
        or os.getenv("GEMINI_API_KEY")
        or os.getenv("GOOGLE_API_KEY")
    )
    openai_key = (
        (api_key if provider == "openai" else None)
        or settings.OPENAI_API_KEY
        or os.getenv("OPENAI_API_KEY")
    )
    temp = temperature if temperature is not None else settings.TEMPERATURE

    # Auto-detection based on configured keys
    if groq_key and selected_provider not in {"mock", "test"}:
        selected_provider = "groq"
    elif gemini_key and selected_provider not in {"mock", "test", "groq"}:
        selected_provider = "gemini"
    elif openai_key and selected_provider not in {"mock", "test", "groq", "gemini"}:
        selected_provider = "openai"

    # 1. Groq Provider
    if selected_provider == "groq":
        if groq_key:
            try:
                from langchain_groq import ChatGroq

                chosen_model = model or settings.GROQ_MODEL
                llm = ChatGroq(
                    model_name=chosen_model,
                    temperature=temp,
                    groq_api_key=groq_key,
                )
                logger.info(f"Initialized Groq Chat LLM with model '{chosen_model}'.")
                return llm
            except Exception as e:
                logger.warning(
                    f"Failed to initialize live Groq LLM: {e}. Falling back to MockChatModel."
                )
                return MockChatModel()
        else:
            logger.info(
                "No GROQ_API_KEY detected in environment. "
                "Using MockChatModel for offline/test execution. "
                "(Set GROQ_API_KEY in .env to connect to live Groq LPU models)"
            )
            return MockChatModel()

    # 2. Google Gemini Provider
    elif selected_provider == "gemini":
        if gemini_key:
            try:
                from langchain_google_genai import ChatGoogleGenerativeAI

                chosen_model = model or settings.GEMINI_LLM_MODEL
                llm = ChatGoogleGenerativeAI(
                    model=chosen_model,
                    temperature=temp,
                    google_api_key=gemini_key,
                )
                logger.info(f"Initialized Google Gemini LLM with model '{chosen_model}'.")
                return llm
            except Exception as e:
                logger.warning(
                    f"Failed to initialize live Google Gemini LLM: {e}. "
                    "Falling back to MockChatModel."
                )
                return MockChatModel()
        else:
            logger.info(
                "No GEMINI_API_KEY / GOOGLE_API_KEY detected in environment. "
                "Using MockChatModel for offline/test execution."
            )
            return MockChatModel()

    # 3. OpenAI Provider
    elif selected_provider == "openai":
        if openai_key:
            try:
                from langchain_openai import ChatOpenAI

                chosen_model = model or settings.OPENAI_LLM_MODEL
                llm = ChatOpenAI(
                    model=chosen_model,
                    temperature=temp,
                    api_key=openai_key,
                )
                logger.info(f"Initialized OpenAI Chat LLM with model '{chosen_model}'.")
                return llm
            except Exception as e:
                logger.warning(
                    f"Failed to initialize live OpenAI LLM: {e}. Falling back to MockChatModel."
                )
                return MockChatModel()
        else:
            logger.info("No OPENAI_API_KEY detected in environment. Using MockChatModel.")
            return MockChatModel()

    elif selected_provider in {"mock", "test"}:
        logger.info("Using MockChatModel provider.")
        return MockChatModel()

    else:
        raise ValueError(
            f"Unsupported LLM provider '{selected_provider}'. Supported providers: 'groq', 'gemini', 'openai', 'mock'."
        )
